export const normalizeCompanySlug = (nameOrSlug) => {
  if (!nameOrSlug) return "";
  const cleaned = nameOrSlug
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, "")
    .replace(/[\s_]+/g, "-");

  // Handle special aliases
  if (cleaned.includes("flipkart") || cleaned.includes("filpkart")) return "flipkart";
  if (cleaned.includes("phonepe") || cleaned.includes("phonepay") || cleaned.includes("phone-pay")) return "phonepe";
  if (cleaned.includes("infosys") || cleaned.includes("infosis")) return "infosys";
  if (cleaned.includes("de-shaw") || cleaned.includes("deshaw") || cleaned.includes("d-e-shaw") || cleaned.includes("de shaw")) return "de-shaw";
  if (cleaned.includes("tower-research")) return "tower-research-capital";
  if (cleaned.includes("jp-morgan") || cleaned.includes("jpmorgan") || cleaned.includes("chase")) return "jp-morgan-chase";
  if (cleaned.includes("goldman")) return "goldman-sachs";
  if (cleaned.includes("morgan-stanley") || cleaned.includes("morganstanley") || cleaned.includes("morgan")) return "morgan-stanley";
  if (cleaned.includes("tcs") || cleaned.includes("tata-consultancy")) return "tcs";
  if (cleaned.includes("hcl") || cleaned.includes("hcltech") || cleaned.includes("hcl-tech")) return "hcltech";
  if (cleaned.includes("tech-mahindra") || cleaned.includes("mahindra")) return "tech-mahindra";
  if (cleaned.includes("meta") || cleaned.includes("facebook")) return "meta";
  if (cleaned.includes("uber")) return "uber";
  if (cleaned.includes("amazon")) return "amazon";
  if (cleaned.includes("stripe")) return "stripe";
  if (cleaned.includes("visa")) return "visa";
  if (cleaned.includes("paytm")) return "paytm";
  if (cleaned.includes("zomato")) return "zomato";
  if (cleaned.includes("zepto")) return "zepto";
  if (cleaned.includes("samsung")) return "samsung";

  return cleaned;
};

